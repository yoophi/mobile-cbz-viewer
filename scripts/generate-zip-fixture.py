"""Generate the public, synthetic CBZ used by on-device ZIP diagnostics."""
import io
import json
from pathlib import Path
import struct
import zipfile
import zlib

def png_chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))


# A valid 1x1 RGBA PNG, including correct chunk checksums.
image = (b'\x89PNG\r\n\x1a\n'
         + png_chunk(b'IHDR', struct.pack('>IIBBBBB', 1, 1, 8, 6, 0, 0, 0))
         + png_chunk(b'IDAT', zlib.compress(b'\x00\xff\xff\xff\xff'))
         + png_chunk(b'IEND', b''))
paths = ['1.png', '한글 폴더/2.png', '한글 폴더/중첩/10.png']
archive = io.BytesIO()
with zipfile.ZipFile(archive, 'w') as output:
    for name, content in [(name, image) for name in paths] + [('notes.txt', b'not an image')]:
        entry = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
        entry.compress_type = zipfile.ZIP_DEFLATED
        entry.external_attr = 0o100644 << 16
        output.writestr(entry, content)


def array(data):
    return 'new Uint8Array([' + ','.join(map(str, data)) + '])'


source = (
    '// Generated by scripts/generate-zip-fixture.py; synthetic PNGs, no private reading material.\n'
    f'export const fixtureBytes = {array(archive.getvalue())};\n'
    f'export const fixturePaths = {json.dumps(paths, ensure_ascii=False)};\n'
    f'export const imageBytes = {array(image)};\n'
)
root = Path(__file__).resolve().parent.parent
(root / 'src/diagnostics/zip-fixture.ts').write_text(source, encoding='utf-8')
